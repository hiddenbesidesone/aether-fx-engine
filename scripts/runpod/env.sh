# Shared setup for the RunPod scripts. Source it, don't run it:  source scripts/runpod/env.sh
#
# Finds ComfyUI and its venv, keeps model caches on the persistent /workspace volume, and
# defines `safe_pip`, which pins torch / torchvision / torchaudio / onnxruntime-gpu / xformers
# to whatever is installed right now so custom-node requirements can't swap them.

COMFY_DIR="${COMFY_DIR:-/workspace/ComfyUI}"
AETHER_REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
STATE_DIR="${STATE_DIR:-/workspace/.aether}"

if [ -z "${VENV:-}" ]; then
    for candidate in "$COMFY_DIR/venv" /workspace/venv; do
        if [ -x "$candidate/bin/python" ]; then VENV="$candidate"; break; fi
    done
fi
if [ ! -x "${VENV:-}/bin/python" ]; then
    echo "error: no ComfyUI venv found in $COMFY_DIR/venv or /workspace/venv (set VENV=/path/to/venv)" >&2
    return 1 2>/dev/null || exit 1
fi
PY="$VENV/bin/python"

# /root is wiped when the pod restarts; /workspace is the network volume.
export TORCH_HOME="${TORCH_HOME:-/workspace/.cache/torch}"   # DINOv2 (TRELLIS), Demucs weights
export HF_HOME="${HF_HOME:-/workspace/.cache/huggingface}"   # Stable Audio, MMAudio vocoder, misc HF downloads
mkdir -p "$TORCH_HOME" "$HF_HOME" "$STATE_DIR"
[ -d /usr/local/cuda/bin ] && export PATH="/usr/local/cuda/bin:$PATH"

ORT_GPU_DEFAULT="1.26.0"  # last onnxruntime-gpu built for CUDA 12 (see docs/runpod_comfyui_liveportrait_setup_guide.md)

pkg_version() {  # pkg_version <dist-name>  -> prints version or nothing
    "$PY" - "$1" <<'EOF'
import sys
from importlib.metadata import version, PackageNotFoundError
try:
    print(version(sys.argv[1]))
except PackageNotFoundError:
    pass
EOF
}

torch_info() {  # prints: <torch base version> <cuda tag e.g. 128> <python tag e.g. cp311> <cxx11abi TRUE/FALSE> <sm e.g. 12.0>
    "$PY" - <<'EOF'
import sys, torch
cuda = (torch.version.cuda or "").replace(".", "")
abi = "TRUE" if torch._C._GLIBCXX_USE_CXX11_ABI else "FALSE"
sm = "%d.%d" % torch.cuda.get_device_capability(0) if torch.cuda.is_available() else "none"
print(torch.__version__.split("+")[0], cuda, f"cp{sys.version_info.major}{sys.version_info.minor}", abi, sm)
EOF
}

write_constraints() {
    PIN_FILE="$STATE_DIR/constraints.txt"
    {
        echo "# generated by scripts/runpod/env.sh -- pins the GPU stack that is installed right now"
        for pkg in torch torchvision torchaudio xformers onnxruntime-gpu; do
            v="$(pkg_version "$pkg")"
            [ -n "$v" ] && echo "$pkg==$v"
        done
        grep -v '^#' "$AETHER_REPO/constraints.txt"
    } > "$PIN_FILE"
    export PIP_CONSTRAINT="$PIN_FILE"
}

safe_pip() {  # safe_pip <pip install args...>  (always under the current pins)
    write_constraints
    "$PY" -m pip install "$@"
}

ensure_torchaudio() {
    # Audio nodes need torchaudio; a bare `pip install torchaudio` pulls a different torch from PyPI.
    [ -n "$(pkg_version torchaudio)" ] && return 0
    read -r TORCH_VER CUDA_TAG _ <<<"$(torch_info)"
    echo "[*] installing torchaudio==$TORCH_VER from the cu$CUDA_TAG index (matches torch)"
    safe_pip "torchaudio==$TORCH_VER" --index-url "https://download.pytorch.org/whl/cu$CUDA_TAG"
}

repair_onnxruntime() {
    # The CPU `onnxruntime` wheel and `onnxruntime-gpu` share one import name; whichever was installed last
    # wins. If a node pulled the CPU one in, InsightFace/LivePortrait silently fall back to CPU (70-min renders).
    local gpu_ver cpu_ver fix=""
    gpu_ver="$(pkg_version onnxruntime-gpu)"
    cpu_ver="$(pkg_version onnxruntime)"
    if [ -n "$cpu_ver" ]; then
        echo "[!] removing CPU onnxruntime $cpu_ver (it shadows onnxruntime-gpu)"
        "$PY" -m pip uninstall -y onnxruntime
        gpu_ver="${gpu_ver:-$ORT_GPU_DEFAULT}"
        fix=1
    fi
    case "$gpu_ver" in
        1.2[7-9]*|1.[3-9][0-9]*|[2-9]*)
            echo "[!] onnxruntime-gpu $gpu_ver targets CUDA 13; pinning $ORT_GPU_DEFAULT"
            gpu_ver="$ORT_GPU_DEFAULT"
            fix=1 ;;
    esac
    if [ -n "$fix" ] && ! PIP_CONSTRAINT="" "$PY" -m pip install -q --force-reinstall --no-deps \
            "onnxruntime-gpu==$gpu_ver"; then
        echo "[!] could not install onnxruntime-gpu==$gpu_ver -- LivePortrait face detection needs it" >&2
        return 1
    fi
    [ -n "$gpu_ver" ] && echo "[✓] onnxruntime-gpu==$gpu_ver"
    return 0
}
